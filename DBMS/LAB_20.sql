--Part – A: 
--1. Display rank of students based on SPI. 
SELECT SNAME,SPI,
RANK() OVER (ORDER BY SPI DESC) AS RANK FROM STUDENT

--2. Display dense rank of students based on SPI. 
SELECT SNAME,SPI,
DENSE_RANK() OVER (ORDER BY SPI DESC) AS RANK FROM STUDENT

--3. Display sequential number for each student record.
SELECT SNAME,SPI,
ROW_NUMBER() OVER (ORDER BY SPI DESC) AS RANK FROM STUDENT

--4. Display branch-wise rank of students. 
SELECT SNAME,SPI,BRANCH,
RANK() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK FROM STUDENT

--5. Display branch-wise dense ranking of students. 
SELECT SNAME,SPI,BRANCH,
DENSE_RANK() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK FROM STUDENT

--6. Display branch-wise sequential numbering of students.
SELECT SNAME,SPI,BRANCH,
ROW_NUMBER() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK FROM STUDENT

--7. Display SNAME, Current SPI, Previous SPI and SPI Difference with previous student in ascending order of SPI.
SELECT SNAME,SPI AS CURRENT_SPI,
LAG(SPI) OVER (ORDER BY SPI ASC) AS PREVIOUS_SPI,
SPI-LAG(SPI) OVER (ORDER BY SPI ASC) FROM STUDENT

--8. Display SNAME, Current SPI, Next SPI and SPI Difference with next student in descending order of SPI.
SELECT SNAME, SPI AS CURRENT_SPI,
LEAD(SPI) OVER (ORDER BY SPI DESC) AS NEXT_SPI,
SPI -  LEAD(SPI)OVER (ORDER BY SPI DESC) AS DIFF
FROM STUDENT

--9. Display top 3 students based on SPI.
SELECT SNAME,SPI
FROM (SELECT SNAME,SPI,ROW_NUMBER() OVER (ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI<=3


--10. Display top 2 students from each branch. 
SELECT SNAME,SPI,BRANCH
FROM (SELECT SNAME,SPI,BRANCH,ROW_NUMBER() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI<=2

 
--Part – B: 
--11. Display 5th highest SPI. 
SELECT SNAME,SPI,BRANCH FROM (SELECT SNAME,SPI,BRANCH, DENSE_RANK() OVER (ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI = 5

--12. Display 6th highest SPI.
SELECT SNAME,SPI,BRANCH FROM (SELECT SNAME,SPI,BRANCH, DENSE_RANK() OVER (ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI = 6

--13. Display students having same ranking.
SELECT DISTINCT SNAME,SPI,BRANCH FROM 
(SELECT DISTINCT SNAME,SPI,BRANCH, 
DENSE_RANK() OVER (ORDER BY SPI DESC) AS RANK_SPI, 
LAG(SPI) OVER (ORDER BY SPI DESC) AS PREVIOUS FROM STUDENT)S
WHERE PREVIOUS = SPI

--14. Display SNAME, Previous SPI, Current SPI and Next SPI based on ascending order of SPI. 
SELECT SNAME, 
LAG(SPI) OVER (ORDER BY SPI ASC) AS PREVIOUS,
SPI,
LEAD(SPI) OVER (ORDER BY SPI ASC) AS NEXT_SPI
FROM STUDENT

--15. Display topper of each branch. 
SELECT SNAME,SPI,BRANCH
FROM (SELECT SNAME,SPI,BRANCH,ROW_NUMBER() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI<=3

--Part – C: 
--16. Display students whose SPI is greater than the previous student and less than the next student.
SELECT SNAME,SPI FROM (SELECT SNAME,SPI,
LAG(SPI) OVER (ORDER BY SPI ASC) AS PREVIOUS,
LAG(SPI) OVER (ORDER BY SPI ASC) AS NEXT_SPI FROM STUDENT)S
WHERE PREVIOUS>SPI AND NEXT_SPI<SPI

--17. Display branch-wise second topper students.
SELECT SNAME,SPI,BRANCH
FROM (SELECT SNAME,SPI,BRANCH,ROW_NUMBER() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK_SPI FROM STUDENT)S
WHERE RANK_SPI=2

--18. Display students whose rank and dense rank are different.
SELECT SNAME,SPI,BRANCH
FROM (SELECT SNAME,SPI,BRANCH,
RANK() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS RANK_SPI, 
DENSE_RANK() OVER (PARTITION BY BRANCH ORDER BY SPI DESC) AS DENSE_RANK_SPI  FROM STUDENT)S
WHERE RANK_SPI != DENSE_RANK_SPI

--19. Display consecutive students having same branch ordered by SPI.
SELECT SNAME,BRANCH,SPI
FROM 
(
SELECT SNAME,BRANCH,SPI,
LAG(BRANCH)OVER(ORDER BY SPI) AS PRE_BR,
LEAD(BRANCH)OVER(ORDER BY SPI) AS NEXT_BR
FROM STUDENT)S

WHERE BRANCH=PRE_BR
OR BRANCH=NEXT_BR
ORDER BY SPI ;

--20. Display students whose SPI difference with previous student is maximum.
