--5. Create a stored procedure to display top N highest paid employees from each department (Value of N 
--is entered by user). 
ALTER PROC SP_SELECT_HIGHEST_PAID_EMPLOYEE
@SALARY INT
AS BEGIN
SELECT DEPARTMENT,SALARY_RANK FROM (SELECT *,ROW_NUMBER() OVER (ORDER BY SALARY DESC) AS SALARY_RANK FROM EMPLOYEE)S
WHERE SALARY_RANK = @SALARY
GROUP BY DEPARTMENT
END

EXEC SP_SELECT_HIGHEST_PAID_EMPLOYEE 5

--6. Create a stored procedure to increase salary department-wise by a given percentage. (User Enter 
--Department Name and %, e.g. Computer 10). 
CREATE PROC SP_INCREASE_SALARY
@PERCENTAGE INT,
@DEPARTMENT VARCHAR(25)

AS BEGIN
UPDATE employee SET SALARY = SALARY + (SALARY * (@PERCENTAGE/100) )WHERE DEPARTMENT = @DEPARTMENT
END

SELECT * FROM employee
EXEC SP_INCREASE_SALARY 10,'IT'

--7. Create a stored procedure to display employees having experience greater than or equal to the entered years. 
CREATE PROC SP_SELECT_BY_EXP
@EXP INT
AS BEGIN
SELECT * FROM EMPLOYEE
WHERE (YEAR(GETDATE()) - JOININGYEAR) > @EXP
END

EXEC SP_SELECT_BY_EXP 1

--8. Create a stored procedure that accepts a number as input and displays details of the last N employees who joined the organization. 
CREATE OR ALTER PROCEDURE SP_LAST_N_EMPLOYEES @N INT
AS
BEGIN
 SET NOCOUNT ON;
 IF @N<1 THROW 50003,'N must be greater than zero.',1;
 SELECT TOP (@N) * FROM EMPLOYEE ORDER BY JOININGYEAR DESC,EID DESC;
END;
GO

-- Part B, 9. Books by author name
CREATE OR ALTER PROCEDURE SP_BOOKS_BY_AUTHOR @AuthorName VARCHAR(100)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT B.*,A.AUTHORNAME FROM BOOK B
 JOIN AUTHOR A ON A.AUTHORID=B.AUTHORID
 WHERE A.AUTHORNAME=@AuthorName;
END;
GO

-- 10. Books published after a given year
CREATE OR ALTER PROCEDURE SP_BOOKS_AFTER_YEAR @Year INT
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM BOOK WHERE PUBLICATIONYEAR>@Year ORDER BY PUBLICATIONYEAR;
END;
GO

-- 11. Authors from country with their books
CREATE OR ALTER PROCEDURE SP_AUTHORS_BOOKS_BY_COUNTRY @Country VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT A.AUTHORID,A.AUTHORNAME,A.COUNTRY,B.BOOKID,B.TITLE,B.PRICE,B.PUBLICATIONYEAR
 FROM AUTHOR A LEFT JOIN BOOK B ON B.AUTHORID=A.AUTHORID
 WHERE A.COUNTRY=@Country;
END;
GO

-- 12. Top N most expensive books with author and publisher
CREATE OR ALTER PROCEDURE SP_TOP_N_EXPENSIVE_BOOKS @N INT
AS
BEGIN
 SET NOCOUNT ON;
 IF @N<1 THROW 50004,'N must be greater than zero.',1;
 SELECT TOP (@N) B.BOOKID,B.TITLE,B.PRICE,B.PUBLICATIONYEAR,
        A.AUTHORNAME,P.PUBLISHERNAME
 FROM BOOK B JOIN AUTHOR A ON A.AUTHORID=B.AUTHORID
 JOIN PUBLISHER P ON P.PUBLISHERID=B.PUBLISHERID
 ORDER BY B.PRICE DESC,B.BOOKID;
END;
GO

-- Part C, 13. Total books by publisher
CREATE OR ALTER PROCEDURE SP_BOOK_COUNT_BY_PUBLISHER @PublisherName VARCHAR(100)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT P.PUBLISHERNAME,COUNT(B.BOOKID) AS TotalBooks
 FROM PUBLISHER P LEFT JOIN BOOK B ON B.PUBLISHERID=P.PUBLISHERID
 WHERE P.PUBLISHERNAME=@PublisherName GROUP BY P.PUBLISHERNAME;
END;
GO

-- 14. Books within price range
CREATE OR ALTER PROCEDURE SP_BOOKS_BY_PRICE_RANGE @MinPrice DECIMAL(8,2),@MaxPrice DECIMAL(8,2)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM BOOK WHERE PRICE BETWEEN @MinPrice AND @MaxPrice ORDER BY PRICE;
END;
GO

-- 15. Delete books by author ID
CREATE OR ALTER PROCEDURE SP_DELETE_BOOKS_BY_AUTHOR @AuthorID INT
AS
BEGIN
 SET NOCOUNT ON;
 DELETE FROM BOOK WHERE AUTHORID=@AuthorID;
 SELECT @@ROWCOUNT AS DeletedBooks;
END;
GO
