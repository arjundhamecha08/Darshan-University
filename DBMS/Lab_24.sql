--1. Create a stored procedure to generate department-wise salary statistics like total salary, average 
--salary, minimum salary, and maximum salary. (User enter only department name) 
CREATE PROC SP_STATISTICS_SALARY_DAPARTMENT
@DEPARTMENT VARCHAR(25)
AS BEGIN
SELECT DEPARTMENT,SUM(SALARY) AS TOTAL_SALARY,AVG(SALARY) AS AVG_SALARY, MIN(SALARY) AS MIN_SALARY, MAX(SALARY) AS MAX_SALARY FROM employee
WHERE DEPARTMENT = @DEPARTMENT
GROUP BY DEPARTMENT
END
EXEC SP_STATISTICS_SALARY_DAPARTMENT 'HR'

--2. Create a stored procedure that accepts a joining year and displays employees who joined that year.
CREATE PROC SP_SELECT_EMPLOYEE_BY_YEAR
@YEAR INT
AS BEGIN
SELECT * FROM employee
WHERE JOININGYEAR = @YEAR
END

EXEC SP_SELECT_EMPLOYEE_BY_YEAR 2026

--3. Create a stored procedure for dynamic employee search using parameters (User may enter partial city 
--name). 
CREATE PROC SP_SELECT_BY_CITY
@CITY VARCHAR(25)
AS BEGIN
SELECT * FROM EMPLOYEE
WHERE CITY LIKE '%' + @CITY +'%'
END
EXEC SP_SELECT_BY_CITY 'R'

